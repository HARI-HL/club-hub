import { INSTITUTION } from "../config/institution.js";

const fmt = (iso) =>
  iso
    ? new Date(iso).toLocaleString("en-IN", {
        timeZone: "Asia/Kolkata",
        day: "2-digit",
        month: "short",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        hour12: false,
      })
    : "-";

/**
 * Builds the On-Duty letter in the browser and downloads it. jsPDF is loaded only when the button is clicked,
 * so it does not slow down the rest of the site.
 */
export async function downloadOdLetter({ event, attendees }) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);

  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 48;
  const now = new Date();
  const ref = `CH/${event.id}/${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}${String(now.getDate()).padStart(2, "0")}`;

  // Header
  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text(INSTITUTION.name.toUpperCase(), W / 2, 56, { align: "center" });
  doc.setFontSize(11);
  doc.text("CLUB HUB / OFFICIAL EVENT ROSTER & ON-DUTY (OD) REQUEST", W / 2, 76, { align: "center" });
  doc.setLineWidth(0.8);
  doc.line(M, 88, W - M, 88);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Ref: ${ref}`, M, 108);
  doc.text(`Date: ${fmt(now.toISOString()).split(",")[0]}`, W - M, 108, { align: "right" });

  doc.text("To,", M, 132);
  doc.text(INSTITUTION.addressedTo, M, 146);

  doc.setFont("helvetica", "bold");
  doc.text(`Subject: Request for On-Duty permission for students attending "${event.title}"`, M, 172, {
    maxWidth: W - M * 2,
  });

  // Body
  doc.setFont("helvetica", "normal");
  const body =
    `Respected Sir/Madam,\n\n` +
    `The ${event.club_name} has organised the event "${event.title}" on ${fmt(event.event_date)}` +
    `${event.venue ? ` at ${event.venue}` : ""}. ` +
    `${attendees.length} student(s) have registered through Club Hub and hold a confirmed seat. ` +
    `We kindly request that On-Duty attendance be granted to the students listed below for the duration of the event.\n\n` +
    `The list is system generated. Each seat was reserved on a first come, first served basis and locked at registration.`;
  const bodyLines = doc.splitTextToSize(body, W - M * 2);
  doc.text(bodyLines, M, 198);
  let y = 198 + bodyLines.length * 12 + 10;

  // Event details
  autoTable(doc, {
    startY: y,
    theme: "grid",
    styles: { font: "helvetica", fontSize: 9, cellPadding: 5, textColor: 20, lineColor: 120 },
    columnStyles: { 0: { fontStyle: "bold", cellWidth: 150, fillColor: [238, 238, 238] } },
    body: [
      ["Club", event.club_name],
      ["Event", event.title],
      ["Date and time", fmt(event.event_date)],
      ["Venue", event.venue || "To be announced"],
      ["Approved participants", `${attendees.length} / ${event.capacity}`],
    ],
    margin: { left: M, right: M },
  });
  y = doc.lastAutoTable.finalY + 18;

  // Students
  autoTable(doc, {
    startY: y,
    theme: "grid",
    head: [["S.No", "Student Name", "Registered Email", "Registration Timestamp", "Verification Status"]],
    body: attendees.map((a, i) => [i + 1, a.name, a.email, fmt(a.registered_at), "CONFIRMED - SEAT LOCKED"]),
    styles: { font: "helvetica", fontSize: 8.5, cellPadding: 4, textColor: 20, lineColor: 120, overflow: "linebreak" },
    headStyles: { fillColor: [20, 20, 24], textColor: 255 },
    columnStyles: { 0: { cellWidth: 34 }, 2: { cellWidth: 140 } },
    margin: { left: M, right: M, bottom: 60 },
  });
  y = doc.lastAutoTable.finalY + 56;

  // Signatures (keep them together on one page)
  if (y > H - 130) {
    doc.addPage();
    y = 90;
  }
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.line(M, y, M + 170, y);
  doc.line(W - M - 190, y, W - M, y);
  doc.text("Club Coordinator / Admin", M, y + 14);
  doc.text("Faculty Advisor / HoD", W - M - 190, y + 14);
  doc.setFontSize(8);
  doc.text(`Club: ${event.club_name}`, M, y + 27);
  doc.text("Seal and signature", W - M - 190, y + 27);

  // Footer on every page
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setFontSize(8);
    doc.setTextColor(100);
    doc.text(`Generated by Club Hub on ${fmt(now.toISOString())} IST  |  Ref ${ref}`, M, H - 28);
    doc.text(`Page ${p} of ${pages}`, W - M, H - 28, { align: "right" });
  }

  const slug = event.title.replace(/[^a-z0-9]+/gi, "_").replace(/^_|_$/g, "").slice(0, 40) || "event";
  doc.save(`OD_Letter_${slug}.pdf`);
}
